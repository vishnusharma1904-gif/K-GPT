"use client";
/* Client-side persistence + export helpers for the chat UI.
   Pins/stars live in localStorage so they work without backend migrations. */

type Msg = { role: "user" | "assistant"; content: string; model?: string; ts?: number };

const KEY_CHATS = "kgpt_pinned_chats";
const keyMsgs = (sid: string) => `kgpt_pinned_msgs_${sid}`;

function read(key: string): string[] {
  if (typeof window === "undefined") return [];
  try { return JSON.parse(localStorage.getItem(key) || "[]"); } catch { return []; }
}
function write(key: string, v: string[]) {
  try { localStorage.setItem(key, JSON.stringify(v)); } catch {}
}

export const pins = {
  chats: () => new Set(read(KEY_CHATS)),
  toggleChat(id: string): boolean {
    const cur = read(KEY_CHATS);
    const next = cur.includes(id) ? cur.filter((x) => x !== id) : [...cur, id];
    write(KEY_CHATS, next);
    return next.includes(id);
  },
  msgs: (sid: string) => new Set(read(keyMsgs(sid))),
  toggleMsg(sid: string, mid: string): boolean {
    const cur = read(keyMsgs(sid));
    const next = cur.includes(mid) ? cur.filter((x) => x !== mid) : [...cur, mid];
    write(keyMsgs(sid), next);
    return next.includes(mid);
  },
};

/* Export a conversation to a Markdown string. */
export function toMarkdown(title: string, messages: Msg[]): string {
  const lines = [`# ${title || "K-GPT conversation"}`, "", `_Exported ${new Date().toLocaleString()}_`, ""];
  for (const m of messages) {
    if (!m.content?.trim()) continue;
    const who = m.role === "user" ? "🧑 You" : `🤖 K-GPT${m.model ? ` (${m.model.split("/").pop()})` : ""}`;
    lines.push(`## ${who}`, "", m.content.trim(), "");
  }
  lines.push("---", "_Generated by K-GPT · KSRMCE Campus AI_");
  return lines.join("\n");
}

export function downloadText(filename: string, text: string, type = "text/markdown") {
  const blob = new Blob([text], { type: `${type};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url; a.download = filename; a.click();
  URL.revokeObjectURL(url);
}

/* Print just the conversation (browser "Save as PDF"). */
export function printConversation(title: string, messages: Msg[]) {
  const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const body = messages
    .filter((m) => m.content?.trim())
    .map((m) => `<div class="m ${m.role}"><div class="who">${m.role === "user" ? "You" : "K-GPT"}</div><div class="c">${esc(m.content)}</div></div>`)
    .join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title || "K-GPT")}</title>
  <style>
    body{font:14px/1.6 -apple-system,Segoe UI,Roboto,sans-serif;max-width:760px;margin:40px auto;padding:0 24px;color:#111}
    h1{font-size:22px;margin:0 0 4px} .sub{color:#666;font-size:12px;margin-bottom:24px}
    .m{margin:0 0 18px;padding:14px 16px;border-radius:12px;white-space:pre-wrap}
    .m.user{background:#eef1ff;border:1px solid #dfe4ff}
    .m.assistant{background:#f7f7f9;border:1px solid #ececf0}
    .who{font-weight:700;font-size:11px;text-transform:uppercase;letter-spacing:.04em;color:#555;margin-bottom:6px}
    @media print{ .m{break-inside:avoid} }
  </style></head><body>
  <h1>${esc(title || "K-GPT conversation")}</h1>
  <div class="sub">Exported ${new Date().toLocaleString()} · KSRMCE Campus AI</div>
  ${body}
  </body></html>`;
  const w = window.open("", "_blank");
  if (!w) return;
  w.document.open(); w.document.write(html); w.document.close();
  setTimeout(() => { w.focus(); w.print(); }, 350);
}
