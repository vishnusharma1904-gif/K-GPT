#!/usr/bin/env python3
"""
K-GPT — generate the SQL that seeds a ready-to-use DEMO account.

WHY THIS EXISTS
    Sign-up is gated two ways in backend/app/routers/auth.py:
      1. the email domain must equal settings.allowed_email_domain
         ("ksrmce.ac.in"), and
      2. every non-admin signup is forced through an email OTP
         (`email_verified` starts false and no token is issued until
         /verify-otp succeeds).
    An interviewer has neither a college address nor access to that inbox, so
    they cannot create an account. Rather than weakening the live gate, this
    inserts ONE pre-verified account directly into the database.

    Nothing in the application source is modified. This only writes a row.

WHY IT'S A GENERATOR AND NOT A .sql FILE
    The row contains a password hash. Committing a fixed hash to a public repo
    hands every reader an offline cracking target for an account that is live
    on your demo. So the credential is generated fresh, printed once to your
    terminal, and never written to disk. Re-run it to rotate.

USAGE
    python deploy/make_demo_user.py                 # random strong password
    python deploy/make_demo_user.py --email a@b.com --password 'chosen'

    Then paste the printed SQL into the Supabase SQL editor
    (Dashboard -> SQL Editor -> New query -> Run).

REQUIREMENTS
    pip install passlib     # already in backend/requirements.txt
"""
from __future__ import annotations

import argparse
import secrets
import string

try:
    from passlib.context import CryptContext
except ImportError:
    raise SystemExit("passlib is required:  pip install passlib")

# Must match backend/app/core/security.py exactly, or login will reject the
# row this script creates.
_pwd = CryptContext(schemes=["pbkdf2_sha256"], deprecated="auto")


def strong_password(n: int = 16) -> str:
    # Ambiguous glyphs removed — this gets read aloud or retyped by an
    # interviewer, so 0/O and 1/l/I are a support problem, not a security win.
    alphabet = (string.ascii_lowercase.replace("l", "")
                + string.ascii_uppercase.replace("O", "").replace("I", "")
                + string.digits.replace("0", "").replace("1", ""))
    return "".join(secrets.choice(alphabet) for _ in range(n))


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate demo-account seed SQL for K-GPT.")
    ap.add_argument("--email", default="demo@ksrmce.ac.in",
                    help="Login email for the demo account (default: %(default)s). "
                         "Keeping it on the college domain means the row is "
                         "consistent with what the signup gate would have produced.")
    ap.add_argument("--password", default=None,
                    help="Password to set. Omit to generate a strong random one.")
    ap.add_argument("--name", default="Demo Reviewer",
                    help="Display name shown in the UI (default: %(default)s).")
    args = ap.parse_args()

    password = args.password or strong_password()
    email = args.email.strip().lower()
    pw_hash = _pwd.hash(password)

    # Column choices, and why:
    #   role='student'          -> shows the product as a real user sees it.
    #                              'admin' would expose the admin panel and
    #                              every other user's data to an interviewer.
    #   sub_status='active' +   -> bypasses the paywall/entitlement check so
    #     sub_expires_at 1yr       chat is usable immediately.
    #   email_verified=true     -> the whole point; skips the OTP the reviewer
    #                              cannot receive.
    #   faculty_approved=true   -> harmless for a student row, but avoids any
    #                              null-vs-false edge in the access checks.
    #   quota_tokens            -> generous but finite, so a stuck client or a
    #                              curious reviewer cannot run up your LLM bill.
    sql = f"""
-- ===================================================================
-- K-GPT demo account  ({email})
-- Generated by deploy/make_demo_user.py — safe to re-run (upserts).
-- ===================================================================
insert into app_users (
    email, full_name, roll_no, password_hash, role,
    sub_status, sub_expires_at, email_verified, faculty_approved,
    quota_tokens, used_tokens, daily_msg_limit
) values (
    '{email}',
    '{args.name}',
    'DEMO',
    '{pw_hash}',
    'student',
    'active',
    now() + interval '365 days',
    true,
    true,
    2000000,
    0,
    300
)
on conflict (email) do update set
    password_hash    = excluded.password_hash,
    sub_status       = 'active',
    sub_expires_at   = now() + interval '365 days',
    email_verified   = true,
    used_tokens      = 0,
    updated_at       = now();
""".strip()

    print(sql)
    print()
    print("=" * 62)
    print("  HAND THESE TO THE INTERVIEWER — shown once, not saved anywhere")
    print("=" * 62)
    print(f"  Email    : {email}")
    print(f"  Password : {password}")
    print("=" * 62)
    print("  Next: paste the SQL above into Supabase -> SQL Editor -> Run.")
    print("  Re-run this script any time to rotate the password.")


if __name__ == "__main__":
    main()
